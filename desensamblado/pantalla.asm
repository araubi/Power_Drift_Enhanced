; MUESTRA_PANTALLA: la pasa a SCREEN 2. Cada tercio se copia por columnas (8 líneas
; seguidas del Spectrum están a 256 bytes) y cada atributo se repite 8 veces como color.
MUESTRA_PANTALLA:
	DI
	LD	HL,0
	CALL	VRAM_ESCRIBE_EN
	LD	HL,PANT_PATRONES
	LD	B,3
LA3C4:
	PUSH	BC
	PUSH	HL
	CALL	COPIA_TERCIO
	POP	HL
	LD	DE,0800h
	ADD	HL,DE
	POP	BC
	DJNZ	LA3C4
	LD	HL,2000h
	CALL	VRAM_ESCRIBE_EN
	LD	HL,PANT_ATRIBUTOS
	LD	DE,0300h
LA3DD:
	LD	A,(HL)
	CALL	ATRIB_A_COLOR
	LD	B,8
LA3E3:
	OUT	(98h),A
	INC	HL
	DEC	HL
	DJNZ	LA3E3
	INC	HL
	DEC	DE
	LD	A,D
	OR	E
	JR	nz,LA3DD
	RET
COPIA_TERCIO:
	LD	BC,0100h
LA3F3:
	PUSH	HL
	CALL	COPIA_COLUMNA
	POP	HL
	INC	HL
	DEC	BC
	LD	A,B
	OR	C
	JR	nz,LA3F3
	RET
