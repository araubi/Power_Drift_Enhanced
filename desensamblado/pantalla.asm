	LD	A,(HL)
	OUT	(98h),A
	INC	H
	NOP
	NOP
	LD	A,(HL)
	OUT	(98h),A
	INC	H
	NOP
	NOP
	LD	A,(HL)
	OUT	(98h),A
	INC	H
	NOP
	NOP
	LD	A,(HL)
	OUT	(98h),A
	INC	H
	NOP
	NOP
	LD	A,(HL)
	OUT	(98h),A
	INC	H
	NOP
	NOP
	LD	A,(HL)
	OUT	(98h),A
	INC	H
	NOP
	NOP
	LD	A,(HL)
	OUT	(98h),A
	INC	H
	NOP
	NOP
	LD	A,(HL)
	OUT	(98h),A
	INC	H
	NOP
	NOP
	RET
ATRIB_A_COLOR:
	PUSH	HL
	PUSH	DE
	PUSH	BC
	PUSH	AF
	LD	HL,0A45Fh
	BIT	6,A
	JR	z,LA43E
	LD	HL,0A467h
LA43E:
	PUSH	HL
	AND	7
	LD	E,A
	LD	D,0
	ADD	HL,DE
	LD	A,(HL)
	RRCA
	RRCA
	RRCA
	RRCA
	LD	C,A
	POP	HL
	POP	AF
	AND	38h
	SRA	A
	SRA	A
	SRA	A
	LD	E,A
	LD	D,0
	ADD	HL,DE
	LD	A,(HL)
	OR	C
	POP	BC
	POP	DE
	POP	HL
	RET
